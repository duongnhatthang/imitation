"""Random-offset grids on the declared observation Box of the continuous tasks.

A random grid (generator `tasks.RANDOM_GRID_GENERATOR`) is a fixed,
parameter-free, dimension-preserving learner restriction for CartPole,
Acrobot, MountainCar and LunarLander (`tasks.RANDOM_GRID_SPECS`). It depends
only on the declared Box, the declared coordinate kinds, the per-axis count
``K`` and the seed: no data, expert action or reward. It is a random-offset
product grid (one uniform offset per coordinate, drawn once), not a uniform
random grouping of a continuum.

Offsets: a local ``np.random.RandomState(seed).random_sample(d)`` draws one
``u_f`` per raw coordinate in coordinate order, pass-through ones included, so
the kinds of other coordinates never shift an offset; every ``K`` shares them,
and grids of different ``K`` are not nested. They are frozen as literals
(`FROZEN_OFFSETS`) and only regenerated by tests.

Coordinate kinds (`GRID_FEATURES`):

* ``linear`` (finite Box ``[lo, hi]``): edges ``lo + (u_f + m) * ((hi - lo) /
  K)`` for ``m = 0..K-1``, so ``K + 1`` half-open cells ``[left, right)``
  including two partial end cells. The end cells extend to infinity, which
  clamps values outside the Box (LunarLander does not enforce its Box). The
  representative is the float32 midpoint of the cell's intersection with
  ``[lo, hi]``.
* ``unbounded`` (Box bounds equal to -/+ float32 max, CartPole's two
  velocities): those bounds are sentinels, never finite ends. At construction
  only, the same grid is built on ``t = 1/2 + atan(x / s) / pi`` with
  ``s = 1`` (raw units, an arbitrary declared scale), and edges and
  t-midpoint representatives are mapped back by ``s * tan(pi * (t - 1/2))``.
* ``circular`` (an Acrobot ``(cos, sin)`` pair, offset of its cos
  coordinate): ``K`` equal arcs ``[2 pi (u + j) / K, 2 pi (u + j + 1) / K)``;
  the representative is the float32 ``(cos, sin)`` of the arc midpoint. A
  pair is assigned by float64 cross products with the frozen edge unit
  vectors: arc ``j`` holds the pair iff ``cross(E_j, v) >= 0`` and
  ``cross(E_(j+1), v) < 0``. ``K = 2`` is one half-plane test against
  ``E_0`` with a dot-product tie break on the dividing line. The zero pair
  (invalid simulator input) and any pair whose tests do not single out one
  arc go to arc 0.
* ``binary`` (LunarLander leg contacts): passed through unchanged.

The ``tan``, ``cos`` and ``sin`` values were generated once
(`generate_libm_tables`) and are frozen in `random_grid_tables`, guarded by
`FROZEN_TABLES_SHA256`, so no platform recomputes them; linear tables are
plain float64 arithmetic. At run time a lookup uses only comparisons and
float64 multiply and subtract on frozen values, the same operations in numpy
(`RandomGridRestriction.apply`) and torch (`GridMask`), so both agree bitwise,
on edges too. Every finite float32 input gives a finite float32 output in the
input dtype, the map is idempotent, and no random number is drawn. Each grid
is pinned by its full descriptor digest (`FROZEN_GRID_SHA256`): a changed
rule, offset, bound or table is refused rather than silently giving a
different mask. `check_box` refuses an observation space whose Box bits differ
from `DECLARED_BOX_BITS`; it is separate from `tasks.describe`, whose records
and digests are unchanged.
"""

