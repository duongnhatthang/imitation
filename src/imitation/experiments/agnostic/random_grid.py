def draw_offsets(env_name: str, seed: int = SEED) -> Tuple[float, ...]:
    """One offset per raw coordinate from a local ``RandomState(seed)``.

    Reads and advances no global numpy or torch random state.
    """
    d = len(DECLARED_BOX_BITS[env_name]["low"])
    return tuple(float(u) for u in np.random.RandomState(seed).random_sample(d))


def linear_table(
    lo: float,
    hi: float,
    u: float,
    k: int,
) -> Tuple[Tuple[float, ...], Tuple[float, ...]]:
    """Edges and float32 representatives of a linear axis (plain arithmetic)."""
    width = (hi - lo) / k
    edges = tuple(lo + (u + m) * width for m in range(k))
    bounds = (lo,) + edges + (hi,)
    centers = tuple(_f32((bounds[i] + bounds[i + 1]) / 2) for i in range(k + 1))
    return edges, centers


def unbounded_table(
    u: float,
    k: int,
    scale: float = UNBOUNDED_SCALE,
) -> Tuple[Tuple[float, ...], Tuple[float, ...]]:
    """Edges and representatives of an unbounded axis; calls ``math.tan``.

    Construction only: the result is frozen in `random_grid_tables`.
    """
    t = [(u + m) / k for m in range(k)]
    edges = tuple(scale * math.tan(math.pi * (tm - 0.5)) for tm in t)
    tb = [0.0] + t + [1.0]
    centers = tuple(
        _f32(scale * math.tan(math.pi * ((tb[i] + tb[i + 1]) / 2 - 0.5)))
        for i in range(k + 1)
    )
    return edges, centers


def circular_table(u: float, k: int) -> Dict[str, Tuple[float, ...]]:
    """Edge unit vectors and float32 arc-midpoint pairs; calls ``math.cos/sin``.

    Construction only: the result is frozen in `random_grid_tables`.
    """
    two_pi = 2.0 * math.pi
    alpha = [two_pi * (u + j) / k for j in range(k)]
    beta = [two_pi * (u + j + 0.5) / k for j in range(k)]
    return {
        "edge_cos": tuple(math.cos(a) for a in alpha),
        "edge_sin": tuple(math.sin(a) for a in alpha),
        "center_cos": tuple(_f32(math.cos(b)) for b in beta),
        "center_sin": tuple(_f32(math.sin(b)) for b in beta),
    }


def _offsets(env_name: str) -> Tuple[float, ...]:
    return tuple(float.fromhex(h) for h in FROZEN_OFFSETS[env_name])


def generate_libm_tables() -> Dict[str, Tuple[float, ...]]:
    """Every ``tan``, ``cos`` and ``sin`` table, keyed ``env/feature/K/array``.

    Construction only: run once to write `random_grid_tables`; tests compare
    it with the frozen tables within a few ulps.
    """
    tables: Dict[str, Tuple[float, ...]] = {}
    for env_name, features in GRID_FEATURES.items():
        offsets = _offsets(env_name)
        for feature in features:
            u = offsets[feature.indices[0]]
            for k in COUNTS:
                key = f"{env_name}/{feature.name}/{k}"
                if feature.kind == "unbounded":
                    edges, centers = unbounded_table(u, k)
                    tables[f"{key}/edges"] = edges
                    tables[f"{key}/centers"] = centers
                elif feature.kind == "circular":
                    for name, values in circular_table(u, k).items():
                        tables[f"{key}/{name}"] = values
    return tables


def encode_tables(tables: Dict[str, Sequence[float]]) -> Dict[str, str]:
    """Base64 of the little-endian float64 bytes of every table."""
    return {
        key: base64.b64encode(np.asarray(values, dtype="<f8").tobytes()).decode()
        for key, values in sorted(tables.items())
    }


def tables_sha256(tables: Dict[str, Sequence[float]]) -> str:
    """Digest of decoded tables, every value as ``float.hex``."""
    return _digest({k: [float(v).hex() for v in vs] for k, vs in tables.items()})


@functools.lru_cache(maxsize=None)
def _frozen_tables_json() -> str:
    tables = {
        key: [
            float(v)
            for v in np.frombuffer(base64.b64decode(text, validate=True), dtype="<f8")
        ]
        for key, text in random_grid_tables.TABLES.items()
    }
    digest = tables_sha256(tables)
    if not digest == FROZEN_TABLES_SHA256 == random_grid_tables.TABLES_SHA256:
        raise RuntimeError(
            f"random grid tables {digest} differ from the frozen "
            f"{FROZEN_TABLES_SHA256}",
        )
    return json.dumps({k: [v.hex() for v in vs] for k, vs in tables.items()})


def frozen_tables() -> Dict[str, Tuple[float, ...]]:
    """The frozen libm tables, verified against `FROZEN_TABLES_SHA256`."""
    data = json.loads(_frozen_tables_json())
    return {k: tuple(float.fromhex(v) for v in vs) for k, vs in data.items()}


