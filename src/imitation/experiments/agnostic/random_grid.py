@dataclasses.dataclass(frozen=True)
class GridAxis:
    """Frozen lookup table of one grid coordinate (or pair)."""

    name: str
    kind: str
    indices: Tuple[int, ...]
    offset: float
    low: Optional[float]
    high: Optional[float]
    scale: Optional[float]
    edges: Tuple[float, ...] = ()
    centers: Tuple[float, ...] = ()
    edge_cos: Tuple[float, ...] = ()
    edge_sin: Tuple[float, ...] = ()
    center_cos: Tuple[float, ...] = ()
    center_sin: Tuple[float, ...] = ()

    @property
    def n_cells(self) -> int:
        if self.kind == "binary":
            return 2
        if self.kind == "circular":
            return len(self.edge_cos)
        return len(self.centers)


def _arc_index(c, s, ec, es, lib):
    """Arc of every ``(c, s)`` pair (1-D float64); same operations per ``lib``."""
    k = ec.shape[0]
    if k == 2:
        cross = ec[0] * s - es[0] * c
        dot = ec[0] * c + es[0] * s
        second = (cross < 0) | ((cross == 0) & (dot < 0))
        return second.astype(np.int64) if lib is np else second.to(th.long)
    parts = []
    for start in range(0, c.shape[0], _CHUNK):
        cc = c[start : start + _CHUNK, None]
        ss = s[start : start + _CHUNK, None]
        cross = ec * ss - es * cc
        ahead = cross >= 0
        if lib is np:
            starts = ahead & ~np.roll(ahead, -1, axis=-1)
            first = np.argmax(starts, axis=-1)
            one = starts.sum(-1) == 1
            parts.append(np.where(one, first, 0).astype(np.int64))
        else:
            starts = ahead & ~th.roll(ahead, -1, dims=-1)
            first = starts.to(th.int32).argmax(-1)
            one = starts.sum(-1) == 1
            parts.append(th.where(one, first, th.zeros_like(first)).to(th.long))
    if lib is np:
        return np.concatenate(parts) if parts else np.zeros(0, dtype=np.int64)
    return th.cat(parts) if parts else th.zeros(0, dtype=th.long, device=c.device)


def _grid_map(wide, axes: Tuple[GridAxis, ...], arrays: List[Dict[str, Any]], lib):
    """Map a float64 ``(rows, d)`` array; ``arrays`` hold each axis' tables."""
    out = wide.clone() if lib is th else wide.copy()
    for axis, table in zip(axes, arrays):
        if axis.kind in ("linear", "unbounded"):
            i = axis.indices[0]
            column = wide[:, i]
            if lib is np:
                idx = np.searchsorted(table["edges"], column, side="right")
            else:
                idx = th.searchsorted(table["edges"], column.contiguous(), right=True)
            out[:, i] = table["centers"][idx]
        elif axis.kind == "circular":
            ic, is_ = axis.indices
            idx = _arc_index(
                wide[:, ic],
                wide[:, is_],
                table["edge_cos"],
                table["edge_sin"],
                lib,
            )
            out[:, ic] = table["center_cos"][idx]
            out[:, is_] = table["center_sin"][idx]
    return out


_TABLE_FIELDS = ("edges", "centers", "edge_cos", "edge_sin", "center_cos", "center_sin")


@dataclasses.dataclass(frozen=True)
class RandomGridRestriction:
    """A frozen random-offset grid map on a continuous observation."""

    restriction_id: str
    env_name: str
    n_bins: int
    seed: int
    generator: str
    rule: str
    obs_shape: Tuple[int, ...]
    box_low_bits: Tuple[str, ...]
    box_high_bits: Tuple[str, ...]
    offsets: Tuple[str, ...]
    axes: Tuple[GridAxis, ...]
    description: str

    def descriptor(self) -> Dict[str, Any]:
        """JSON-serializable full descriptor (every edge and representative)."""
        return json.loads(json.dumps(dataclasses.asdict(self)))

    @functools.cached_property
    def descriptor_sha256(self) -> str:
        """Digest of the full descriptor; saved with restricted checkpoints."""
        return _digest(self.descriptor())

    @property
    def nominal_cells(self) -> int:
        """Product of the per-coordinate cell counts (binary flags count 2)."""
        return int(np.prod([a.n_cells for a in self.axes], dtype=object))

    @functools.cached_property
    def _np_tables(self) -> List[Dict[str, np.ndarray]]:
        return [
            {
                f: np.array(getattr(a, f), dtype=np.float64)
                for f in _TABLE_FIELDS
                if getattr(a, f)
            }
            for a in self.axes
        ]

    def check_input(self, shape: Tuple[int, ...], dtype: str) -> None:
        if len(shape) < 1 or tuple(shape[-1:]) != self.obs_shape:
            raise ValueError(
                f"{self.restriction_id}: input shape {tuple(shape)} does not end "
                f"in {self.obs_shape}",
            )
        if dtype not in INPUT_DTYPES:
            raise ValueError(
                f"{self.restriction_id}: input dtype {dtype} is not one of "
                f"{INPUT_DTYPES}",
            )

    def check_finite(self, finite: bool) -> None:
        if not finite:
            raise ValueError(f"{self.restriction_id}: input is not finite")

    def check_box(self, space: Any) -> None:
        """Refuse an observation space other than the declared float32 Box.

        Raises:
            tasks.TaskMismatch: If ``space`` is not a float32 Box of the
                declared shape whose low and high bits equal the declared ones.
        """
        if (
            not isinstance(space, gym.spaces.Box)
            or space.dtype != np.float32
            or tuple(space.shape) != self.obs_shape
        ):
            raise tasks.TaskMismatch(
                f"{self.restriction_id}: observation space {space} is not a "
                f"float32 Box of shape {self.obs_shape}",
            )
        low, high = float32_bits(space.low), float32_bits(space.high)
        if low != self.box_low_bits or high != self.box_high_bits:
            raise tasks.TaskMismatch(
                f"{self.restriction_id}: Box bits low {low} high {high} differ "
                f"from the declared low {self.box_low_bits} high "
                f"{self.box_high_bits}",
            )

    def apply(self, obs: np.ndarray) -> np.ndarray:
        """Return the gridded copy of ``obs`` (last axis is the feature axis)."""
        obs = np.asarray(obs)
        self.check_input(obs.shape, str(obs.dtype))
        self.check_finite(bool(np.all(np.isfinite(obs))))
        wide = obs.astype(np.float64).reshape(-1, self.obs_shape[0])
        out = _grid_map(wide, self.axes, self._np_tables, np)
        return out.reshape(obs.shape).astype(obs.dtype)


class GridMask(th.nn.Module):
    """Torch form of a `RandomGridRestriction`; non-persistent table buffers."""

    def __init__(self, grid: RandomGridRestriction):
        super().__init__()
        self.grid = grid
        self._names: List[Dict[str, str]] = []
        for a, tables in enumerate(grid._np_tables):
            names = {}
            for field, values in tables.items():
                name = f"axis{a}_{field}"
                self.register_buffer(name, th.tensor(values), persistent=False)
                names[field] = name
            self._names.append(names)

    def forward(self, obs: th.Tensor) -> th.Tensor:
        dtype = str(obs.dtype).replace("torch.", "")
        self.grid.check_input(tuple(obs.shape), dtype)
        self.grid.check_finite(bool(th.all(th.isfinite(obs))))
        wide = obs.to(th.float64).reshape(-1, self.grid.obs_shape[0])
        arrays = [
            {field: getattr(self, name) for field, name in names.items()}
            for names in self._names
        ]
        out = _grid_map(wide, self.grid.axes, arrays, th)
        return out.reshape(obs.shape).to(obs.dtype)


def _check_kinds(env_name: str, low: Sequence[str], high: Sequence[str]) -> None:
    """Declared kinds must agree with the declared Box bits."""
    task = tasks.get_task(env_name)
    covered = sorted(i for f in GRID_FEATURES[env_name] for i in f.indices)
    if covered != list(range(task.obs_dim)) or len(low) != task.obs_dim:
        raise RuntimeError(f"{env_name}: grid features do not cover the observation")
    for f in GRID_FEATURES[env_name]:
        lo = [bits_to_float(low[i]) for i in f.indices]
        hi = [bits_to_float(high[i]) for i in f.indices]
        sentinel = [
            low[i] == NEG_FLOAT32_MAX_BITS and high[i] == FLOAT32_MAX_BITS
            for i in f.indices
        ]
        if f.kind == "unbounded":
            ok = all(sentinel)
        elif f.kind == "circular":
            ok = len(f.indices) == 2 and lo == [-1.0, -1.0] and hi == [1.0, 1.0]
        elif f.kind == "binary":
            ok = lo == [0.0] and hi == [1.0]
        else:
            ok = f.kind == "linear" and not any(sentinel) and lo[0] < hi[0]
        if not ok:
            raise RuntimeError(f"{env_name}: {f.name} is not a valid {f.kind} axis")


def _check_axis(axis: GridAxis) -> None:
    """Finite, ordered tables whose representatives map to their own cell."""
    tables = [getattr(axis, f) for f in _TABLE_FIELDS]
    if not all(math.isfinite(v) for t in tables for v in t):
        raise RuntimeError(f"{axis.name}: table is not finite")
    if axis.kind in ("linear", "unbounded"):
        edges, centers = axis.edges, axis.centers
        if any(b <= a for a, b in zip(edges, edges[1:])):
            raise RuntimeError(f"{axis.name}: edges are not increasing")
        for i, c in enumerate(centers):
            if c != _f32(c) or bisect.bisect_right(edges, c) != i:
                raise RuntimeError(f"{axis.name}: representative {i} leaves its cell")
    elif axis.kind == "circular":
        cc = np.array(axis.center_cos, dtype=np.float64)
        cs = np.array(axis.center_sin, dtype=np.float64)
        if any(v != _f32(v) for v in axis.center_cos + axis.center_sin):
            raise RuntimeError(f"{axis.name}: representative is not float32")
        idx = _arc_index(
            cc,
            cs,
            np.array(axis.edge_cos),
            np.array(axis.edge_sin),
            np,
        )
        if not np.array_equal(idx, np.arange(len(cc))):
            raise RuntimeError(f"{axis.name}: representative leaves its arc")


def _build(spec: tasks.RandomGridSpec) -> RandomGridRestriction:
    env_name, k = spec.env_name, spec.n_bins
    bits = DECLARED_BOX_BITS[env_name]
    _check_kinds(env_name, bits["low"], bits["high"])
    if spec.seed != SEED or spec.generator != GENERATOR or k not in COUNTS:
        raise RuntimeError(f"{spec.restriction_id}: not a frozen grid spec")
    offsets = _offsets(env_name)
    if not all(0.0 < u < 1.0 for u in offsets):
        raise RuntimeError(f"{env_name}: an offset is not inside (0, 1)")
    libm = frozen_tables()
    axes = []
    for f in GRID_FEATURES[env_name]:
        i = f.indices[0]
        key = f"{env_name}/{f.name}/{k}"
        common = dict(name=f.name, kind=f.kind, indices=f.indices, offset=offsets[i])
        if f.kind == "linear":
            lo, hi = bits_to_float(bits["low"][i]), bits_to_float(bits["high"][i])
            edges, centers = linear_table(lo, hi, offsets[i], k)
            axis = GridAxis(
                **common, low=lo, high=hi, scale=None, edges=edges, centers=centers
            )
        elif f.kind == "unbounded":
            axis = GridAxis(
                **common,
                low=None,
                high=None,
                scale=UNBOUNDED_SCALE,
                edges=libm[f"{key}/edges"],
                centers=libm[f"{key}/centers"],
            )
        elif f.kind == "circular":
            axis = GridAxis(
                **common,
                low=None,
                high=None,
                scale=None,
                **{n: libm[f"{key}/{n}"] for n in _TABLE_FIELDS[2:]},
            )
        else:
            axis = GridAxis(**common, low=None, high=None, scale=None)
        _check_axis(axis)
        axes.append(axis)
    kinds = ", ".join(f"{f.name}: {f.kind}" for f in GRID_FEATURES[env_name])
    return RandomGridRestriction(
        restriction_id=spec.restriction_id,
        env_name=env_name,
        n_bins=k,
        seed=spec.seed,
        generator=spec.generator,
        rule=RANDOM_GRID_RULE,
        obs_shape=(len(bits["low"]),),
        box_low_bits=tuple(bits["low"]),
        box_high_bits=tuple(bits["high"]),
        offsets=tuple(FROZEN_OFFSETS[env_name]),
        axes=tuple(axes),
        description=(
            f"{env_name} learner sees every coordinate replaced by the "
            f"representative of its cell in a random-offset grid of the declared "
            f"Box with K={k} per axis (K+1 cells on linear and unbounded axes, "
            f"K arcs on angle pairs; seed {spec.seed}, {spec.generator}); "
            f"kinds: {kinds}."
        ),
    )


def is_grid_id(restriction_id: Any) -> bool:
    return isinstance(restriction_id, str) and restriction_id in tasks.RANDOM_GRID_SPECS


@functools.lru_cache(maxsize=None)
def get_grid(restriction_id: str) -> RandomGridRestriction:
    """The registered grid, verified against `FROZEN_GRID_SHA256`.

    Raises:
        ValueError: If ``restriction_id`` is not a registered grid.
        RuntimeError: If the rebuilt descriptor or the libm tables differ from
            their frozen digests.
    """
    if not is_grid_id(restriction_id):
        raise ValueError(f"{restriction_id!r} is not a random grid")
    grid = _build(tasks.RANDOM_GRID_SPECS[restriction_id])
    frozen = FROZEN_GRID_SHA256.get(restriction_id)
    if grid.descriptor_sha256 != frozen:
        raise RuntimeError(
            f"{restriction_id}: descriptor {grid.descriptor_sha256} differs from "
            f"the frozen {frozen}; the rule, Box, offsets or tables changed",
        )
    return grid


def describe_box(env_name: str) -> Dict[str, Any]:
    """Box bits of the original factory ``env_utils.make_env``, checked.

    This builds the environment, so it is the pre-launch check of a grid
    environment; it never changes `tasks.describe`.

    Raises:
        ValueError: If ``env_name`` has no random grid.
        tasks.TaskMismatch: If the factory's Box differs from the declared one.
    """
    if env_name not in GRID_FEATURES:
        raise ValueError(f"{env_name!r} has no random grid")
    venv = env_utils.make_env(env_name, 1, np.random.default_rng(0))
    try:
        space = venv.observation_space
    finally:
        venv.close()
    grid = get_grid(tasks.RANDOM_GRID_CANDIDATES[env_name][0])
    grid.check_box(space)
    return {
        "env_name": env_name,
        "low_bits": list(grid.box_low_bits),
        "high_bits": list(grid.box_high_bits),
        "feature_kinds": {f.name: f.kind for f in GRID_FEATURES[env_name]},
        "box_sha256": _digest([list(grid.box_low_bits), list(grid.box_high_bits)]),
    }
