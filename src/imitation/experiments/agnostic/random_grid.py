def _digest(value: Any) -> str:
    return tasks._digest(value)


def bits_to_float(bits: str) -> float:
    """The float32 value of an 8-digit hex bit pattern, as a Python float."""
    word = np.array([int(bits, 16)], dtype=np.uint32)
    return float(word.view(np.float32)[0])


def float32_bits(values: Any) -> Tuple[str, ...]:
    """8-digit hex bit patterns of float32 values."""
    array = np.ascontiguousarray(np.asarray(values, dtype=np.float32).reshape(-1))
    return tuple(f"{int(w):08x}" for w in array.view(np.uint32))


def _f32(value: float) -> float:
    with np.errstate(over="raise"):
        return float(np.float32(value))


